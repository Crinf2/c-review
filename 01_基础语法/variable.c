#include<stdio.h>
int main()
{
	//变量保存数据的内存空间，变量是空间并非数据
	int a = 10; //定义变量a并赋值为10
	int b = 20; //定义变量b并赋值为20
	int c = a + b; //定义变量c并赋值为a+b的结果
	printf("a = %d, b = %d, c = %d\n", a, b, c);
	//变量只能保存一个数据，保存新的数据会覆盖原来的数据
	a = 30; //将变量a的值修改为30
	printf("a = %d, b = %d, c = %d\n", a, b, c);
	//变量具有作用范围，变量只能在定义它的函数中使用，其他函数无法使用该变量





	//计算机的存储规则 以二进制存储
	//
	return 0;
}